package app.mirsad.core.ml.train

import app.mirsad.core.ml.FeatureHasher
import app.mirsad.core.ml.LinearModel
import app.mirsad.core.ml.ModelClassifier
import app.mirsad.core.ml.ModelFormat
import java.io.File
import java.io.FileOutputStream
import kotlin.random.Random

/**
 * Entry point of `./gradlew :core:trainModel`: `main(dataDir, outputModelPath)`.
 * Regenerates data/generated_messages.csv, evaluates on a stratified 20 % hold-out, writes
 * data/evaluation.md, retrains on everything and writes the model file.
 */
fun main(args: Array<String>) {
    require(args.size >= 2) { "usage: TrainerMainKt <dataDir> <outputModelPath>" }
    Trainer.run(File(args[0]), File(args[1]), ::println)
}

object Trainer {
    const val SEED_FILE = "seed_messages.csv"
    const val GENERATED_FILE = "generated_messages.csv"
    const val LEGIT_SUITE_FILE = "legit_suite.csv"
    const val EVALUATION_FILE = "evaluation.md"

    /** Rows in seed + generated, balanced between scam and legit. */
    const val TARGET_TOTAL = 1400
    const val HOLD_OUT_FRACTION = 0.2
    const val SPLIT_SEED = 7
    const val THRESHOLD = 0.5

    fun run(dataDir: File, outputModel: File, log: (String) -> Unit) {
        val seeds = LabelledMessage.readCsv(File(dataDir, SEED_FILE))
        require(seeds.isNotEmpty()) { "no seed rows in ${File(dataDir, SEED_FILE)}" }
        val generated = regenerate(dataDir, seeds)
        val all = seeds + generated
        log("rows: seed=${seeds.size} generated=${generated.size} total=${all.size} " +
            "scam=${all.count { it.isScam }} legit=${all.count { !it.isScam }}")

        val (train, heldOut) = stratifiedSplit(all, HOLD_OUT_FRACTION, SPLIT_SEED)
        log("hold-out: train=${train.size} test=${heldOut.size}")
        val heldOutModel = trainModel(train, log)
        val evaluation = Evaluation.of(ModelClassifier(heldOutModel), heldOut, THRESHOLD)
        log(evaluation.summary())

        val suiteFile = File(dataDir, LEGIT_SUITE_FILE)
        val suite = if (suiteFile.exists()) LabelledMessage.readCsv(suiteFile) else emptyList()
        val suiteClassifier = ModelClassifier(heldOutModel)
        val suiteFlagged = suite.filter { suiteClassifier.scoreScam(it.text) >= THRESHOLD }
        if (suite.isNotEmpty()) {
            log("legit suite: ${suiteFlagged.size} of ${suite.size} rows score >= $THRESHOLD")
            suiteFlagged.forEach { log("  flagged (%.3f): %s".format(suiteClassifier.scoreScam(it.text), it.text.take(90))) }
        }

        File(dataDir, EVALUATION_FILE).writeText(evaluationMarkdown(all, train, heldOut, evaluation, suite, suiteFlagged), Charsets.UTF_8)
        log("wrote ${File(dataDir, EVALUATION_FILE)}")

        val finalModel = trainModel(all) {}
        outputModel.parentFile?.mkdirs()
        FileOutputStream(outputModel).use { ModelFormat.write(finalModel, it) }
        log("wrote $outputModel (${outputModel.length()} bytes, ${finalModel.modelVersion})")
    }

    /** Writes generated_messages.csv so that seed + generated reach [TARGET_TOTAL] rows, balanced by label. */
    fun regenerate(dataDir: File, seeds: List<LabelledMessage>): List<LabelledMessage> {
        val perLabel = TARGET_TOTAL / 2
        val scamNeeded = (perLabel - seeds.count { it.isScam }).coerceAtLeast(0)
        val legitNeeded = (perLabel - seeds.count { !it.isScam }).coerceAtLeast(0)
        val generated = MessageGenerator().generate(scamNeeded, legitNeeded)
        LabelledMessage.writeCsv(File(dataDir, GENERATED_FILE), generated)
        return generated
    }

    fun trainModel(rows: List<LabelledMessage>, log: (String) -> Unit): LinearModel {
        val samples = rows.map { LogisticRegressionTrainer.toSample(it, FeatureHasher.NUM_BUCKETS) }
        return LogisticRegressionTrainer().train(samples, log)
    }

    fun stratifiedSplit(rows: List<LabelledMessage>, holdOut: Double, seed: Int): Pair<List<LabelledMessage>, List<LabelledMessage>> {
        val rnd = Random(seed)
        val train = ArrayList<LabelledMessage>()
        val test = ArrayList<LabelledMessage>()
        for ((_, group) in rows.groupBy { it.label }) {
            val shuffled = group.shuffled(rnd)
            val n = Math.round(shuffled.size * holdOut).toInt()
            test += shuffled.take(n)
            train += shuffled.drop(n)
        }
        return train.shuffled(rnd) to test.shuffled(rnd)
    }

    private fun evaluationMarkdown(
        all: List<LabelledMessage>,
        train: List<LabelledMessage>,
        heldOut: List<LabelledMessage>,
        evaluation: Evaluation,
        suite: List<LabelledMessage>,
        suiteFlagged: List<LabelledMessage>,
    ): String = buildString {
        appendLine("# Classifier evaluation: ${ModelFormat.DEFAULT_MODEL_VERSION}")
        appendLine()
        appendLine("Generated by `./gradlew :core:trainModel` (`app.mirsad.core.ml.train.TrainerMainKt`). Do not edit by hand.")
        appendLine()
        appendLine("**All data here is synthetic**: 22 hand-written seed messages plus templated variants from")
        appendLine("`MessageGenerator` (seed ${MessageGenerator.DEFAULT_SEED}). Variants of the same templates appear on both sides of the")
        appendLine("split, so these numbers measure how well the model fits the templates, not real-world accuracy.")
        appendLine("Evaluation on real, anonymised police case data is the intended next step; no accuracy claim should")
        appendLine("be made from this table.")
        appendLine()
        appendLine("## Data")
        appendLine()
        appendLine("| | scam | legit | total |")
        appendLine("|---|---|---|---|")
        for (lang in listOf("en", "ar", "ar-latn")) {
            val rows = all.filter { it.lang == lang }
            appendLine("| $lang | ${rows.count { it.isScam }} | ${rows.count { !it.isScam }} | ${rows.size} |")
        }
        appendLine("| all | ${all.count { it.isScam }} | ${all.count { !it.isScam }} | ${all.size} |")
        appendLine()
        appendLine("Stratified split (seed $SPLIT_SEED): ${train.size} training rows, ${heldOut.size} held-out rows (${(HOLD_OUT_FRACTION * 100).toInt()} %).")
        appendLine()
        appendLine("## Held-out metrics")
        appendLine()
        append(evaluation.markdownTable())
        appendLine()
        appendLine("## Legitimate-message suite (`legit_suite.csv`)")
        appendLine()
        if (suite.isEmpty()) {
            appendLine("Not found.")
        } else {
            appendLine("Model-only check (no rules): ${suiteFlagged.size} of ${suite.size} hand-written legitimate rows score >= $THRESHOLD.")
            for (row in suiteFlagged) appendLine("- `${row.sender}`: ${row.text.take(100).replace("\n", " ")}")
        }
        appendLine()
        appendLine("## Model")
        appendLine()
        appendLine("Hashed character 2-5-grams and word unigrams (${FeatureHasher.NUM_BUCKETS} buckets, signed FNV-1a/fmix32), ")
        appendLine("L2-normalised counts, logistic regression with L2 trained by seeded SGD. The shipped model is retrained on all rows.")
    }
}
